-- 租户套餐（开通模板）：与 MySQL V1.0.235 平行

CREATE TABLE IF NOT EXISTS sys_tenant_package (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_code    varchar(64)  NOT NULL,
    package_name    varchar(128) NOT NULL,
    package_status  smallint     NOT NULL DEFAULT 1,
    is_default      smallint     NOT NULL DEFAULT 0,
    description     varchar(500),
    sort            integer      NOT NULL DEFAULT 0,
    remark          varchar(500),
    create_by       bigint,
    create_time     timestamp,
    create_dept     bigint,
    update_by       bigint,
    update_time     timestamp,
    del_flag        bigint       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tenant_package_code_active
    ON sys_tenant_package (package_code, del_flag);

CREATE TABLE IF NOT EXISTS sys_tenant_package_item (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id   bigint       NOT NULL,
    item_type    varchar(32)  NOT NULL,
    item_code    varchar(128) NOT NULL,
    item_value   text,
    sort         integer      NOT NULL DEFAULT 0,
    create_by    bigint,
    create_time  timestamp,
    create_dept  bigint,
    update_by    bigint,
    update_time  timestamp,
    del_flag     bigint       NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_tenant_package_item_pkg ON sys_tenant_package_item (package_id, del_flag);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tenant_package_item
    ON sys_tenant_package_item (package_id, item_type, item_code, del_flag);

CREATE TABLE IF NOT EXISTS sys_tenant_package_grant (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       bigint       NOT NULL,
    package_id      bigint       NOT NULL,
    package_code    varchar(64)  NOT NULL,
    snapshot_json   text         NOT NULL,
    grant_status    varchar(32)  NOT NULL DEFAULT 'ACTIVE',
    granted_at      timestamp    NOT NULL,
    create_by       bigint,
    create_time     timestamp,
    create_dept     bigint,
    update_by       bigint,
    update_time     timestamp,
    del_flag        bigint       NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_tenant_package_grant_tenant ON sys_tenant_package_grant (tenant_id, del_flag);

