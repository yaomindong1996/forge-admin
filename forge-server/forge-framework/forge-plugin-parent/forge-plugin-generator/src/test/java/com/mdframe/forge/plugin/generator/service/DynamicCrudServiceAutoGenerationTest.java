    @Test
    @DisplayName("form designer snake_case binding sync then create generates customer code")
    void formDesignerSnakeCaseBindingSyncThenCreateGeneratesCustomerCode() throws Exception {
        LowcodeModelSchema modelSchema = new LowcodeModelSchema();
        modelSchema.setTableName("biz_customer");
        LowcodeFieldSchema customerCode = new LowcodeFieldSchema();
        customerCode.setField("customerCode");
        customerCode.setColumnName("customer_code");
        customerCode.setLabel("客户编码");
        customerCode.setDataType("varchar");
        LowcodeFieldSchema customerName = new LowcodeFieldSchema();
        customerName.setField("customerName");
        customerName.setColumnName("customer_name");
        customerName.setLabel("客户名称");
        customerName.setDataType("varchar");
        modelSchema.setFields(new ArrayList<>(List.of(customerCode, customerName)));

        FormDesignerSchemaDTO formSchema = new FormDesignerSchemaDTO();
        formSchema.setComponents(List.of(Map.of(
                "id", "cmp_code",
                "componentKey", "input",
                "label", "输入框",
                "fieldBinding", Map.of("mode", "field", "fieldCode", "customer_code"),
                "props", Map.of(
                        "generation", Map.of(
                                "enabled", true,
                                "ruleCode", "customer_code",
                                "trigger", "ON_CREATE",
                                "fillPolicy", "EMPTY_ONLY"
                        )
                ),
                "visibility", Map.of("readonly", true, "hidden", true),
                "layout", Map.of("span", 1)
        )));
        LowcodePageSchema pageSchema = new LowcodePageSchema();
        pageSchema.setZones(new ArrayList<>());
        new BusinessObjectRuntimeFormProjector(value -> false)
                .applyFormDesignerSchemaToEditZone(pageSchema, modelSchema, formSchema);

        AiCrudConfig config = new AiCrudConfig();
        config.setTenantId(1L);
        config.setConfigKey("biz_customer");
        config.setObjectCode("BIZ_CUSTOMER");
        config.setTableName("biz_customer");
        config.setModelSchema(objectMapper.writeValueAsString(modelSchema));
        config.setEditSchema("[{\"field\":\"customerName\",\"label\":\"客户名称\",\"type\":\"input\"}]");

        repository.setColumnMapping(Map.of(
                "customerCode", "customer_code",
                "customer_code", "customer_code",
                "customerName", "customer_name",
                "customer_name", "customer_name"
        ));
        codeRuleService.setGeneratedCode("customer_code", "C000007");
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("customerName", "端到端客户");
        Set<String> allowedFields = new LinkedHashSet<>(Set.of("customerName"));

        applyAutoGeneratedFields(config, data, allowedFields);

        assertEquals("C000007", data.get("customerCode"));
        assertEquals("C000007", data.get("customer_code"));
        assertEquals(1, codeRuleService.getGenerateCalls());
        assertTrue(allowedFields.contains("customerCode"));
    }

    @SuppressWarnings("unchecked")
    private void applyAutoGeneratedFields(AiCrudConfig config,
                                          Map<String, Object> data,
                                          Set<String> allowedFields) {
        generatedFieldPolicy.applyAutoGeneratedFields(config, data, allowedFields);
    }

