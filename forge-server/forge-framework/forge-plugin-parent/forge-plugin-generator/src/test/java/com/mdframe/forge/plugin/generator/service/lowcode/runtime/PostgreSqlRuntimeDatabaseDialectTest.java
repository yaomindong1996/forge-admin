package com.mdframe.forge.plugin.generator.service.lowcode.runtime;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

@DisplayName("PostgreSQL runtime dialect contracts")
class PostgreSqlRuntimeDatabaseDialectTest {

    private final PostgreSqlRuntimeDatabaseDialect dialect = new PostgreSqlRuntimeDatabaseDialect();

    @Test
    @DisplayName("supports postgres aliases")
    void supportsAliases() {
        assertTrue(dialect.supports("PostgreSQL"));
        assertTrue(dialect.supports("postgres"));
        assertFalse(dialect.supports("mysql"));
    }

    @Test
    @DisplayName("maps lowcode types to PG sql types")
    void resolveSqlTypes() {
        assertEquals("timestamp", dialect.resolveSqlType("datetime", 0, null));
        assertEquals("smallint", dialect.resolveSqlType("tinyint", 0, null));
        assertEquals("jsonb", dialect.resolveSqlType("json", 0, null));
        assertEquals("text", dialect.resolveSqlType("longtext", 0, null));
        assertEquals("varchar(64)", dialect.resolveSqlType("varchar", 64, null));
        assertEquals("numeric(18,2)", dialect.resolveSqlType("decimal", 0, "18,2"));
    }

    @Test
    @DisplayName("ddl identifiers are lowercased and quoted")
    void ddlIdentifiersLowercase() {
        assertEquals("\"biz_order\"", dialect.ddlIdentifier("Biz_Order"));
        assertEquals("\"field_name\"", dialect.ddlIdentifier("Field_Name"));
    }

    @Test
    @DisplayName("boolean switch default becomes numeric 1 for smallint")
    void booleanDefaultUsesNumeric() {
        String definition = dialect.columnDefinition(new RuntimeDatabaseDialect.DdlColumn(
                "field_switch",
                "smallint",
                true,
                true,
                null,
                "开关",
                false
        ));
        assertTrue(definition.contains("DEFAULT 1"), definition);
        assertFalse(definition.contains("DEFAULT 'true'"), definition);
        assertFalse(definition.contains("GENERATED BY DEFAULT AS IDENTITY"), definition);
    }

    @Test
    @DisplayName("snowflake primary key does not force identity")
    void snowflakePrimaryKeyWithoutIdentity() {
        String definition = dialect.columnDefinition(new RuntimeDatabaseDialect.DdlColumn(
                "id",
                "bigint",
                true,
                null,
                null,
                "主键",
                false
        ));
        assertTrue(definition.contains("\"id\" bigint"), definition);
        assertTrue(definition.contains("NOT NULL"), definition);
        assertFalse(definition.contains("IDENTITY"), definition);
    }

    @Test
    @DisplayName("create table + comments + index after statements")
    void createTableSnapshot() {
        var id = new RuntimeDatabaseDialect.DdlColumn("id", "bigint", true, null, null, "主键", false);
        var name = new RuntimeDatabaseDialect.DdlColumn("name", "varchar(64)", true, null, null, "名称", false);
        String create = dialect.createTableSql("Biz_Order", List.of(
                dialect.columnDefinition(id),
                dialect.columnDefinition(name),
                dialect.primaryKeyConstraint("Biz_Order", "id")
        ), "业务订单");
        assertTrue(create.startsWith("CREATE TABLE IF NOT EXISTS \"biz_order\""), create);
        assertTrue(create.contains("\"name\" varchar(64) NOT NULL"), create);

        List<String> after = dialect.afterCreateTableSql(
                "Biz_Order",
                "业务订单",
                List.of(id, name),
                List.of(new RuntimeDatabaseDialect.IndexDefinition("idx_biz_order_name", List.of("name"), false))
        );
        assertTrue(after.stream().anyMatch(sql -> sql.contains("COMMENT ON TABLE \"biz_order\"")), after.toString());
        assertTrue(after.stream().anyMatch(sql -> sql.contains("COMMENT ON COLUMN \"biz_order\".\"name\"")), after.toString());
        assertTrue(after.stream().anyMatch(sql -> sql.contains("CREATE INDEX \"idx_biz_order_name\" ON \"biz_order\"")), after.toString());
    }

    @Test
    @DisplayName("modify column splits into type/default/nullability/comment statements")
    void modifyColumnSplits() {
        var column = new RuntimeDatabaseDialect.DdlColumn(
                "amount", "numeric(18,2)", false, null, null, "金额", false);
        List<String> statements = dialect.modifyColumnSql("biz_order", column);
        assertEquals(4, statements.size());
        assertTrue(statements.get(0).contains("TYPE numeric(18,2)"), statements.get(0));
        assertTrue(statements.get(1).contains("DROP DEFAULT"), statements.get(1));
        assertTrue(statements.get(2).contains("DROP NOT NULL"), statements.get(2));
        assertTrue(statements.get(3).contains("COMMENT ON COLUMN"), statements.get(3));
    }

    @Test
    @DisplayName("string aggregate uses string_agg")
    void stringAggregate() {
        assertEquals(
                "string_agg(\"name\"::text, '、' ORDER BY \"id\")",
                dialect.stringAggregate("\"name\"", "\"id\"", "、"));
    }
}
