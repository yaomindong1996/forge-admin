-- Minimal schema for the production purchase, role, resource and DataScope Mapper XML.
CREATE TABLE sys_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT NOT NULL,
    parent_id BIGINT, resource_name VARCHAR(80), resource_type INT NOT NULL,
    path VARCHAR(160), perms VARCHAR(100) NOT NULL, api_method VARCHAR(10), api_url VARCHAR(160),
    client_code VARCHAR(16) NOT NULL, sort INT NOT NULL DEFAULT 0,
    component VARCHAR(160), feature_code VARCHAR(80), icon VARCHAR(80), is_external INT,
    sso_enabled INT, sso_target_client VARCHAR(20), open_target VARCHAR(20), is_public INT,
    keep_alive INT, always_show INT, redirect VARCHAR(160), remark VARCHAR(160), min_user_type INT,
    create_by BIGINT, create_time TIMESTAMP, create_dept BIGINT, update_by BIGINT, update_time TIMESTAMP,
    visible INT NOT NULL DEFAULT 1, menu_status INT NOT NULL DEFAULT 1, del_flag BIGINT NOT NULL DEFAULT 0,
    UNIQUE (tenant_id, resource_type, perms, client_code, del_flag)
);
CREATE TABLE sys_role (
    id BIGINT PRIMARY KEY, tenant_id BIGINT NOT NULL, role_key VARCHAR(40),
    org_scope_type INT DEFAULT 1 NOT NULL, role_status INT DEFAULT 1 NOT NULL,
    data_scope INT NOT NULL, del_flag BIGINT DEFAULT 0 NOT NULL
);
CREATE TABLE sys_role_org (id BIGINT PRIMARY KEY, tenant_id BIGINT, role_id BIGINT, org_id BIGINT);
CREATE TABLE sys_role_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL, role_id BIGINT NOT NULL, resource_id BIGINT NOT NULL,
    create_time TIMESTAMP, UNIQUE (tenant_id, role_id, resource_id)
);
CREATE TABLE sys_user_org (user_id BIGINT PRIMARY KEY, tenant_id BIGINT, org_id BIGINT);
CREATE TABLE sys_user_org_role (tenant_id BIGINT, user_id BIGINT, org_id BIGINT, role_id BIGINT);
CREATE TABLE sys_org (id BIGINT PRIMARY KEY, ancestors VARCHAR(80), del_flag BIGINT DEFAULT 0 NOT NULL);
CREATE TABLE sys_region_code (code VARCHAR(12) PRIMARY KEY, parent_code VARCHAR(12));
CREATE TABLE sys_role_data_scope (id BIGINT PRIMARY KEY, tenant_id BIGINT, role_id BIGINT, org_id BIGINT, create_time TIMESTAMP);
CREATE TABLE sys_role_module_data_scope (
    id BIGINT PRIMARY KEY, tenant_id BIGINT, role_id BIGINT, module_code VARCHAR(80), data_scope INT,
    create_by BIGINT, create_time TIMESTAMP, create_dept BIGINT, update_by BIGINT, update_time TIMESTAMP
);
CREATE TABLE sys_data_scope_config (
    id BIGINT PRIMARY KEY, tenant_id BIGINT, resource_code VARCHAR(80), resource_name VARCHAR(80),
    mapper_method VARCHAR(180), table_alias VARCHAR(12), user_id_column VARCHAR(40), org_id_column VARCHAR(40),
    tenant_id_column VARCHAR(40), region_code_column VARCHAR(40), user_region_column VARCHAR(40), user_table_alias VARCHAR(12),
    flow_related_visible BOOLEAN DEFAULT FALSE, flow_business_type VARCHAR(80), record_id_column VARCHAR(40),
    enabled INT, remark VARCHAR(160), create_by BIGINT, create_time TIMESTAMP, create_dept BIGINT,
    update_by BIGINT, update_time TIMESTAMP, del_flag BIGINT DEFAULT 0 NOT NULL
);
CREATE TABLE sys_user (id BIGINT PRIMARY KEY, real_name VARCHAR(60), username VARCHAR(60), del_flag BIGINT DEFAULT 0 NOT NULL);
CREATE TABLE sample_purchase_order (
    id BIGINT PRIMARY KEY, tenant_id BIGINT, order_no VARCHAR(40), title VARCHAR(80), supplier_name VARCHAR(80),
    amount_cent BIGINT, purchase_items VARCHAR(500), need_date DATE, status VARCHAR(20),
    applicant_id BIGINT, applicant_name VARCHAR(60), applicant_dept_id BIGINT, applicant_dept_name VARCHAR(60),
    business_key VARCHAR(80), process_instance_id VARCHAR(80), dept_leader_id BIGINT, engineering_manager_id BIGINT,
    countersign_user_ids VARCHAR(100), cc_role_keys VARCHAR(100), arrival_list_file_ids VARCHAR(100),
    applicant_modify_remark VARCHAR(200), dept_leader_remark VARCHAR(200), engineering_manager_remark VARCHAR(200),
    countersign_remark VARCHAR(200), reject_reason VARCHAR(200), remark VARCHAR(200), create_by BIGINT,
    create_time TIMESTAMP, create_dept BIGINT, update_by BIGINT, update_time TIMESTAMP, del_flag BIGINT DEFAULT 0 NOT NULL
);

